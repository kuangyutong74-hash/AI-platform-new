class MoMoAgent(BaseAgent):
    """沫沫智能体 — AI海豚管家，温柔耐心善于鼓励"""

    def __init__(self):
        super().__init__(
            name="沫沫",
            system_prompt=MOMO_SYSTEM_PROMPT,
            fallback_responses=MOMO_FALLBACK,
        )

    def generate(self, player_input: str, context: dict) -> str:
        """生成沫沫回复，确保回复温暖鼓励"""
        if "chat_history" not in context:
            context["chat_history"] = "暂无"
        if "current_round" not in context:
            context["current_round"] = "3"
        if "harmony" not in context:
            context["harmony"] = "70"
        if "is_final" not in context:
            context["is_final"] = "true"

        return super().generate(player_input, context)

    def generate_final_summary(self, harmony: float, round_num: int, chat_history: list) -> str:
        """生成保底总结 — 根据和解度选择不同类型的总结语"""
        context = {
            "current_round": str(round_num),
            "harmony": str(int(harmony)),
            "is_final": "true",
            "chat_history": chat_history if chat_history else "暂无",
        }

        if self.ai_enabled and self.client:
            try:
                player_input = f"和解度{int(harmony)}%，共{round_num}轮对话。请根据和解度给出温暖的总结。"
                return self.generate(player_input, context)
            except Exception:
                pass

        # 降级：根据和解度选择不同风格的总结
        if harmony >= 100:
            import random
            return random.choice(self.fallback_responses.get("success_final", ["🎉 太棒了！"]))
        else:
            import random
            return random.choice(self.fallback_responses.get("final_round", ["🤝 好啦好啦……"]))


