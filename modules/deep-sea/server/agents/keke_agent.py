class KeKeAgent(BaseAgent):
    """壳壳智能体 — 寄居蟹，内向敏感"""

    def __init__(self):
        super().__init__(
            name="壳壳",
            system_prompt=KEKE_SYSTEM_PROMPT,
            fallback_responses=KEKE_FALLBACK,
        )

    def generate(self, player_input: str, context: dict) -> str:
        """生成壳壳回复，确保回复符合角色性格"""
        # 确保上下文包含必要字段
        if "personality" not in context:
            context["personality"] = "敏感型"
        if "chat_history" not in context:
            context["chat_history"] = "暂无"
        if "anger_level" not in context:
            context["anger_level"] = 60
        if "current_round" not in context:
            context["current_round"] = 1

        return super().generate(player_input, context)


